// Builds public/icons.js from Phosphor's filled icon set. Run: node scripts/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const SRC = path.resolve('node_modules/@phosphor-icons/core/assets');
const NAMES = {
  // resident actions
  camera: 'fill/camera-fill', microphone: 'fill/microphone-fill', text: 'fill/chat-text-fill', siren: 'fill/siren-fill',
  phone: 'fill/phone-fill', send: 'fill/paper-plane-right-fill', check: 'fill/check-fill', x: 'fill/x-fill', back: 'fill/arrow-left-fill',
  pin: 'fill/map-pin-fill', sun: 'fill/sun-fill', moon: 'fill/moon-fill', auto: 'fill/circle-half-fill', sparkle: 'fill/sparkle-fill',
  megaphone: 'fill/megaphone-fill', offline: 'fill/cell-signal-slash-fill', wind: 'fill/wind-fill', firstaid: 'fill/first-aid-fill',
  run: 'fill/person-simple-run-fill', lock: 'fill/lock-fill', silent: 'fill/ear-slash-fill', people: 'fill/users-three-fill',
  user: 'fill/user-fill', clock: 'fill/clock-fill', gauge: 'fill/gauge-fill', broadcast: 'fill/broadcast-fill', eye: 'fill/eye-fill',
  image: 'fill/image-fill', video: 'fill/video-camera-fill', waveform: 'fill/waveform-fill', bell: 'fill/bell-ringing-fill',
  verified: 'fill/seal-check-fill', caret: 'fill/caret-right-fill', reset: 'fill/arrows-clockwise-fill', play: 'fill/play-fill', map: 'fill/map-trifold-fill', chart: 'fill/chart-bar-fill', bolt: 'fill/lightning-fill', heat: 'fill/thermometer-hot-fill', storm: 'fill/cloud-lightning-fill', layers: 'fill/stack-fill', filter: 'fill/funnel-fill', person: 'fill/person-fill', hand: 'fill/hand-palm-fill', warning: 'fill/warning-fill', shield: 'fill/shield-warning-fill', search: 'fill/list-magnifying-glass-fill',
  // categories
  fire: 'fill/fire-fill', smoke: 'fill/cloud-fog-fill', flood: 'fill/waves-fill', power: 'fill/lightning-slash-fill', gas: 'fill/gas-can-fill',
  road: 'fill/traffic-cone-fill', other: 'fill/warning-fill', drone: 'fill/drone-fill', vessel: 'fill/boat-fill', crane: 'fill/crane-fill',
  medical: 'fill/first-aid-fill', security: 'fill/shield-warning-fill', hazmat: 'fill/flask-fill', anchor: 'fill/anchor-fill', airplane: 'fill/airplane-tilt-fill',
};

const out = {};
for (const [name, file] of Object.entries(NAMES)) {
  const svg = fs.readFileSync(path.join(SRC, `${file}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+fill="[^"]*"/g, '').trim();
  out[name] = inner;
}
const js = `// Generated by scripts/build-icons.mjs from Phosphor Icons (MIT). Do not edit by hand.
export const ICONS = ${JSON.stringify(out, null, 0)};
export function icon(name, size = 24, extra = '') {
  const body = ICONS[name] || ICONS.other;
  return \`<svg viewBox="0 0 256 256" width="\${size}" height="\${size}" fill="currentColor" aria-hidden="true" \${extra}>\${body}</svg>\`;
}
export function paintIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) el.innerHTML = icon(el.dataset.icon, el.dataset.size || 24);
}
`;
fs.writeFileSync('public/icons.js', js);
console.log(`wrote public/icons.js with ${Object.keys(out).length} icons, ${(js.length / 1024).toFixed(1)} KB`);
